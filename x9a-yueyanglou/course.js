/* ============ 天气滑块：0 阴雨 → 100 晴明 → 200 月夜 ============ */
const WEATHER = [
  { at: 0, k: 'yin', name: '淫雨霏霏', mood: '感极而悲', tone: '悲' },
  { at: 100, k: 'qing', name: '春和景明', mood: '其喜洋洋', tone: '喜' },
  { at: 200, k: 'yue', name: '皓月千里', mood: '此乐何极', tone: '喜' },
];

function setWeather(slide, v) {
  const pics = slide.querySelectorAll('.yy-pic');
  // 0~100：阴雨淡出、晴明淡入；100~200：晴明淡出、月夜淡入
  const op = [Math.max(0, 1 - v / 100), v <= 100 ? v / 100 : Math.max(0, (200 - v) / 100), Math.max(0, (v - 100) / 100)];
  pics.forEach((p, i) => { p.style.opacity = op[i]; });
  slide.querySelector('.yy-rain').style.opacity = Math.max(0, 1 - v / 60);
  const near = WEATHER.reduce((a, b) => (Math.abs(b.at - v) < Math.abs(a.at - v) ? b : a));
  slide.querySelectorAll('.yy-text').forEach((t) => t.classList.toggle('now', t.dataset.k === (near.k === 'yin' ? 'yin' : 'qing')));
  slide.querySelectorAll('.yy-text p[data-k]').forEach((p) => p.classList.toggle('hi', p.dataset.k === near.k));
  // 心情指针：-60°（悲）到 +60°（喜），阴雨到晴明之间连续转动
  const deg = Math.min(60, -60 + Math.min(v, 100) * 1.2);
  slide.querySelector('.yy-needle').style.transform = `rotate(${deg}deg)`;
  slide.querySelector('.yy-mood b').textContent = near.mood;
  slide.querySelector('.yy-mood').classList.toggle('sad', near.tone === '悲');
  slide.querySelector('.yy-name').textContent = near.name;
}

function initWeather() {
  const slide = document.querySelector('.s-weather');
  const range = slide.querySelector('#yyRange');
  Narrative.fillRain(slide.querySelector('.yy-rain .rain'));
  range.addEventListener('input', () => setWeather(slide, +range.value));
  slide.querySelectorAll('[data-go]').forEach((b) => b.addEventListener('click', () => {
    range.value = b.dataset.go;
    setWeather(slide, +range.value);
  }));
  setWeather(slide, 0);
}

/* 按步骤推动滑块：第 1 步阴雨，第 2 步晴明，第 3 步月夜 */
function updateWeather(slide, step) {
  if (!slide.classList.contains('s-weather') || step < 1 || step > 3) return;
  const v = [0, 100, 200][step - 1];
  slide.querySelector('#yyRange').value = v;
  setWeather(slide, v);
}

function initWords() {
  const box = document.getElementById('words');
  box.innerHTML = WORDS.map((w) => `<button type="button" class="wcard"><small>${w.k}</small><b>${w.w}</b><span class="wa">${w.a}<em>${w.e}</em></span></button>`).join('');
  box.addEventListener('click', (e) => {
    const c = e.target.closest('.wcard');
    if (c) c.classList.toggle('open');
  });
}

window.LESSON = {
  init() {
    Narrative.init({ moments: MOMENTS });
    Poem.init();
    initWeather();
    initWords();
  },
  onRender(slide, step) {
    Narrative.onRender(slide, step);
    updateWeather(slide, step);
  },
};
