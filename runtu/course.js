/* 四件新鲜事：点卡片看闰土的品质 */
function initThings() {
  const box = document.getElementById('things');
  if (!box) return;
  box.addEventListener('click', (e) => {
    const card = e.target.closest('.thing');
    if (card) card.classList.toggle('open');
  });
}

