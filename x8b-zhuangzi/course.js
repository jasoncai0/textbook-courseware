function initWords() {
  const box = document.getElementById('words');
  box.innerHTML = WORDS.map((w) => `<button type="button" class="wcard"><small>${w.k}</small><b>${w.w}</b><span class="wa">${w.a}<em>${w.e}</em></span></button>`).join('');
  box.addEventListener('click', (e) => {
    const c = e.target.closest('.wcard');
    if (c) c.classList.toggle('open');
  });
}

/* 辩论拔河：每回合后绳结的位置（0 = 庄子一侧，100 = 惠子一侧） */
const ROPE = [50, 38, 62, 42, 72, 25, 25];
function updateDebate(slide, step) {
  const mark = slide.querySelector('#dbMark');
  if (mark) mark.style.left = `${ROPE[Math.min(step, ROPE.length - 1)]}%`;
}

/* 尺度动画：用 slide 上的 data-zz 驱动 CSS */
function updateScale(slide, step) {
  if (slide.classList.contains('s-scale')) slide.dataset.zz = step;
}

window.LESSON = {
  init() {
    Narrative.init({});
    Poem.init();
    initWords();
  },
  onRender(slide, step) {
    Narrative.onRender(slide, step);
    updateScale(slide, step);
    updateDebate(slide, step);
  },
};
