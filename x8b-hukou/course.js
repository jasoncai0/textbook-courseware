function initFeels() {
  const box = document.getElementById('hkNotes');
  box.innerHTML = FEELS.map((f, i) => `<button type="button" class="hk-note"><i>${i + 1}</i><span class="s">${f.s}</span><span class="a"><b>${f.k}</b>${f.a}</span></button>`).join('');
  box.addEventListener('click', (e) => {
    const c = e.target.closest('.hk-note');
    if (c) c.classList.toggle('open');
  });
}

