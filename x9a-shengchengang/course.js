function initLines() {
  const detail = document.getElementById('lnDetail');
  document.getElementById('lines').addEventListener('click', (e) => {
    const n = e.target.closest('.nd');
    if (!n) return;
    document.querySelectorAll('.nd').forEach((x) => x.classList.toggle('cur', x === n));
    detail.textContent = NODE_TEXT[n.dataset.k];
  });
}

