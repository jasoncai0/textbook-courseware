/* 移步换景：当前一站的画面和说明 */
function updateWalk(slide, step) {
  if (!slide.classList.contains('s-walk')) return;
  const k = Math.max(1, Math.min(step, 6));
  const picK = Math.min(k, 5);
  slide.querySelectorAll('.ys-pic').forEach((p) => p.classList.toggle('now', +p.dataset.k === picK));
  slide.querySelectorAll('.ys-cap').forEach((c) => c.classList.toggle('now', step > 0 && +c.dataset.k === k));
  slide.querySelectorAll('.ys-stop').forEach((s) => s.classList.toggle('cur', +s.dataset.step === step));
  slide.querySelector('.ys-view').classList.toggle('cold', step >= 5);
}

/* 小鱼动静演示 */
function initFish() {
  const tank = document.getElementById('fishTank');
  const set = (mode) => { tank.className = `fish-tank ${mode}`; };
  document.getElementById('fishStill').onclick = () => set('still');
  document.getElementById('fishGo').onclick = () => set('go');
  document.getElementById('fishBack').onclick = () => set('back');
}

window.LESSON = {
  init() {
    Narrative.init({ picks: PICKS, sort: SORT, kinds: KINDS, moments: MOMENTS });
    Poem.init();
    initFish();
  },
  onRender(slide, step) {
    Narrative.onRender(slide, step);
    updateWalk(slide, step);
  },
};
