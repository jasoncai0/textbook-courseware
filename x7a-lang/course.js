function initWords() {
  const tabs = document.getElementById('wTabs');
  const grid = document.getElementById('wGrid');
  const kinds = Object.keys(WORDS);
  tabs.innerHTML = kinds.map((k) => `<button type="button" class="btn" data-k="${k}">${k}</button>`).join('');
  const show = (k) => {
    tabs.querySelectorAll('.btn').forEach((b) => b.classList.toggle('solid', b.dataset.k === k));
    grid.innerHTML = WORDS[k].map((c) => `<button type="button" class="wcard"><b>${c.w}</b>${c.ex.map((e) => {
      const [q, a] = e.split('　→ ');
      return `<span>${q}${a ? `<em>${a}</em>` : ''}</span>`;
    }).join('')}</button>`).join('');
  };
  tabs.addEventListener('click', (e) => { const b = e.target.closest('[data-k]'); if (b) show(b.dataset.k); });
  grid.addEventListener('click', (e) => { const c = e.target.closest('.wcard'); if (c) c.classList.toggle('open'); });
  show(kinds[0]);
}

