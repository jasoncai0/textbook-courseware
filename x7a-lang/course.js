function initChain() {
  const gloss = document.getElementById('gloss');
  document.getElementById('lanes').addEventListener('click', (e) => {
    const v = e.target.closest('.verb');
    if (!v) return;
    document.querySelectorAll('.verb.cur').forEach((x) => x.classList.remove('cur'));
    v.classList.add('cur');
    gloss.innerHTML = `<b>${v.classList.contains('tu') ? '屠户' : '狼'} · ${v.textContent}</b>：${v.dataset.gloss}`;
  });
}

