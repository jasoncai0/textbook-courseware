const WQ = [
  ['有<em>闻</em>而传之者……', '闻：听说'],
  ['国人<em>道</em>之，<em>闻</em>之于宋君。', '道：讲述；闻：使听到（报告）'],
  ['天，积气耳，<em>亡</em>处<em>亡</em>气。', '亡：同“无”，没有'],
  ['<em>只使</em>坠，亦不能有所<em>中伤</em>。', '只使：纵使，即使；中伤：伤害'],
  ['<em>奈何</em>忧其坏？', '奈何：为何，为什么'],
];
function initWq() {
  const box = document.getElementById('wqList');
  box.innerHTML = WQ.map(([q, a], i) => `<button type="button" class="wq"><span class="n">${i + 1}</span><span class="q">${q}</span><span class="a">${a}</span></button>`).join('');
  box.addEventListener('click', (e) => { const b = e.target.closest('.wq'); if (b) b.classList.toggle('open'); });
}

function initWorry() {
  const ans = document.getElementById('worryAns');
  const end = document.getElementById('worryEnd');
  const all = [...document.querySelectorAll('.worry')];
  document.getElementById('worries').addEventListener('click', (e) => {
    const w = e.target.closest('.worry');
    if (!w) return;
    w.classList.add('popped');
    ans.innerHTML = `<b>晓之者：</b>${w.dataset.a}`;
    end.classList.toggle('show', all.every((x) => x.classList.contains('popped')));
  });
}

