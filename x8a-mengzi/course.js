function initChain() {
  const box = document.getElementById('chain');
  const way = document.getElementById('chainWay');
  let c = 0;
  let shown = 1;
  const draw = () => {
    const ch = CHAINS[c];
    box.innerHTML = ch.links.slice(0, shown).map((l, i) => `${i ? '<span class="arrow">↓</span>' : ''}<div class="link"><b>${l.k}</b><span>${l.s}</span></div>`).join('');
    way.innerHTML = shown >= ch.links.length ? ch.way : '下一环是什么？先说一说，再展开。';
    document.getElementById('chainNext').disabled = shown >= ch.links.length;
    document.querySelectorAll('#chainTabs [data-c]').forEach((b) => b.classList.toggle('solid', +b.dataset.c === c));
  };
  document.getElementById('chainTabs').addEventListener('click', (e) => {
    const t = e.target.closest('[data-c]');
    if (t) { c = +t.dataset.c; shown = 1; draw(); return; }
    if (e.target.closest('#chainNext')) { shown = Math.min(CHAINS[c].links.length, shown + 1); draw(); }
  });
  draw();
}

