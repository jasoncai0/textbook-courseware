function buildCxs() {
  const svg = document.getElementById('cxsMap');
  svg.querySelector('.tents').innerHTML = Array.from({ length: 18 }, (_, i) => {
    const x = 440 + (i % 6) * 26 + (Math.floor(i / 6) % 2) * 13;
    const y = 335 + Math.floor(i / 6) * 22;
    return `<g class="pop" style="animation-delay:${(i * 0.06).toFixed(2)}s"><path d="M${x - 10} ${y + 10} L${x} ${y - 6} L${x + 10} ${y + 10} Z" fill="#e8e1d0"/><circle cx="${x}" cy="${y + 5}" r="2.6" fill="#ffc94a"/></g>`;
  }).join('');
  svg.querySelector('.snow').innerHTML = Array.from({ length: 60 }, (_, i) =>
    `<circle class="flake" cx="${(i * 47) % 620}" cy="${-10 - (i * 13) % 60}" r="${1.4 + (i % 3) * 0.7}" fill="#fff" style="animation-delay:${((i * 0.17) % 3).toFixed(2)}s"/>`).join('');
}

