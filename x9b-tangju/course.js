/* 皮影戏台：点台词，说话的人亮起，显示品读 */
function initTheater() {
  const list = document.getElementById('tjLines');
  const stage = list.closest('.slide');
  list.innerHTML = SAYS.map((s, i) => `<button type="button" class="tj-say-btn ${s.who}" data-i="${i}"><small>${s.name}</small>${s.t}</button>`).join('');
  list.addEventListener('click', (e) => {
    const btn = e.target.closest('.tj-say-btn');
    if (!btn) return;
    const s = SAYS[+btn.dataset.i];
    list.querySelectorAll('.tj-say-btn').forEach((b) => b.classList.toggle('on', b === btn));
    stage.querySelector('.fig-q').classList.toggle('speak', s.who === 'q');
    stage.querySelector('.fig-t').classList.toggle('speak', s.who === 't');
    stage.querySelector('#tjWho').textContent = s.name;
    stage.querySelector('#tjSay').textContent = s.t;
    stage.querySelector('#tjAna').textContent = s.a;
    stage.querySelector('#tjLine').className = `tj-line ${s.who}`;
  });
}

function initWords() {
  const box = document.getElementById('words');
  box.innerHTML = WORDS.map((w) => `<button type="button" class="wcard"><small>${w.k}</small><b>${w.w}</b><span class="wq">${w.e}</span><span class="wa">${w.a}</span></button>`).join('');
  box.addEventListener('click', (e) => {
    const c = e.target.closest('.wcard');
    if (c) c.classList.toggle('open');
  });
}

