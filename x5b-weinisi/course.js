/* 课后第 3 题：去掉比喻读一读 */
function initFigToggle() {
  const btn = document.getElementById('figToggle');
  btn.addEventListener('click', () => {
    const plain = btn.closest('.slide').classList.toggle('plain');
    btn.textContent = plain ? '恢复原句' : '去掉比喻读一读';
  });
}

window.LESSON = {
  init() {
    Narrative.init({ kinds: KINDS, sort: SORT_ITEMS, moments: MOMENTS });
    initFigToggle();
  },
  onRender: (slide, step) => Narrative.onRender(slide, step),
};
