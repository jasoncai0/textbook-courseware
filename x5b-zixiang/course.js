function initTry() {
  const svg = document.getElementById('zxSvg');
  const res = document.getElementById('zxRes');
  document.querySelector('.zx-try').addEventListener('click', (e) => {
    const btn = e.target.closest('[data-res]');
    if (!btn) return;
    svg.dataset.res = btn.dataset.res;
    res.textContent = RESULTS[btn.dataset.res];
    document.querySelectorAll('.zx-try .btn').forEach((b) => b.classList.toggle('solid', b === btn));
  });
}

