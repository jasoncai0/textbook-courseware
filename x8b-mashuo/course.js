/* 思考探究二：称谓高亮 */
function initNames() {
  const text = document.getElementById('msText');
  document.getElementById('msWays').addEventListener('click', (e) => {
    const b = e.target.closest('button[data-k]');
    if (!b) return;
    const k = b.dataset.k;
    const on = !b.classList.contains('on');
    document.querySelectorAll('#msWays button').forEach((x) => x.classList.toggle('on', on && x === b));
    text.querySelectorAll('i[data-k]').forEach((i) => i.classList.toggle('hl', on && i.dataset.k === k));
  });
}

window.LESSON = {
  init() {
    Narrative.init({ sort: SORT, kinds: KINDS });
    Poem.init();
    initNames();
  },
  onRender(slide, step) {
    Narrative.onRender(slide, step);
  },
};
