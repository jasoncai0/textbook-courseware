let segIdx = 0;
const esc = (s) => s.replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]));

// 一段 → 句子分类标注：感叹句 / 问句 / 括号现场
function markPara(p) {
  return p.split(/(（[^）]*）)/).map((part) => (part.startsWith('（')
    ? `<span class="sc">${esc(part)}</span>`
    : esc(part).replace(/[^！？。；：]*?[！？]/g, (m) => `<span class="${m.endsWith('！') ? 'ex' : 'q'}">${m}</span>`))).join('');
}

function showSeg(i) {
  segIdx = i;
  const s = SEGS[i];
  document.querySelectorAll('#jySegs .btn').forEach((b, k) => b.classList.toggle('solid', k === i));
  document.getElementById('jyText').innerHTML = s.paras.map((k) => `<p><sup>${k + 1}</sup>${markPara(PARAS[k])}</p>`).join('');
  document.getElementById('jyText').scrollTop = 0;
  document.getElementById('jyBar').style.height = `${s.level}%`;
  document.getElementById('jyMood').textContent = s.mood;
  document.getElementById('jyGuide').innerHTML = s.guide.map((g) => `<p class="tip">${g}</p>`).join('');
}

function initRead() {
  document.getElementById('jySegs').innerHTML = SEGS.map((s, i) => `<button class="btn" type="button" data-i="${i}">${s.name}</button>`).join('');
  document.getElementById('jySegs').addEventListener('click', (e) => {
    const b = e.target.closest('[data-i]');
    if (b) showSeg(+b.dataset.i);
  });
  document.querySelectorAll('[data-mk]').forEach((b) => b.addEventListener('click', () => {
    const on = document.getElementById('jyText').classList.toggle(`show-${b.dataset.mk}`);
    b.classList.toggle('solid', on);
  }));
  showSeg(0);
}

/* 括号里的现场：从课文统计 */
function initClaps() {
  const all = PARAS.flatMap((p, i) => (p.match(/（[^）]*）/g) || []).map((m) => ({ m, i })));
  const heat = (m) => (m.includes('长时间') ? 4 : m.includes('热烈') ? 3 : m.includes('鼓掌') ? 2 : 1);
  document.getElementById('jyClaps').innerHTML = all.map(({ m, i }) => `<span class="h${heat(m)}"><small>第 ${i + 1} 段</small>${m}</span>`).join('');
  document.getElementById('clapN').textContent = all.length;
}

