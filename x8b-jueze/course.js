function initParas() {
  const box = document.getElementById('jzParas');
  box.innerHTML = PARAS.map((p, i) => `<div class="jz-p${i === 0 ? ' open' : ''}"><button type="button" class="jz-h"><i>${i + 1}</i>${p.h}</button><p>${p.t.replace(/（[^）]*）/g, (m) => `<span class="sc">${m}</span>`)}</p></div>${i === 0 || i === 6 ? '<p class="jz-omit">…………</p>' : ''}`).join('');
  box.addEventListener('click', (e) => {
    const h = e.target.closest('.jz-h');
    if (!h) return;
    const card = h.parentElement;
    const open = !card.classList.contains('open');
    box.querySelectorAll('.jz-p').forEach((c) => c.classList.remove('open'));
    card.classList.toggle('open', open);
  });
}

