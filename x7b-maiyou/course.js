function initWords() {
  const grid = document.getElementById('wordGrid');
  const show = (tab) => {
    grid.innerHTML = WORDS[tab].map((c) => `<button class="word" type="button"><b>${c.w}</b><span class="wa">${c.a}</span>${c.e.map((x) => `<span class="we">${x}</span>`).join('')}</button>`).join('');
    document.querySelectorAll('.word-tabs .btn').forEach((b) => b.classList.toggle('solid', b.dataset.tab === tab));
  };
  document.querySelector('.word-tabs').addEventListener('click', (e) => {
    const b = e.target.closest('[data-tab]');
    if (b) show(b.dataset.tab);
  });
  grid.addEventListener('click', (e) => {
    const w = e.target.closest('.word');
    if (w) w.classList.toggle('open');
  });
  show('shi');
}

