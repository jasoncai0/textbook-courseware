function showPart(i) {
  const p = PARTS[i];
  document.querySelectorAll('.ay-band button').forEach((b, k) => b.classList.toggle('cur', k === i));
  document.getElementById('ayGist').innerHTML = `<div class="ay-pic" style="background-image:url(assets/${p.pic}.jpg)"></div><p class="tip"><b>${p.k}：</b>${p.gist}</p><p class="tip gold">${p.tip}</p>`;
  const box = document.getElementById('ayText');
  box.innerHTML = p.paras.map((k) => `<p${k === 0 ? ' class="call"' : ''}>${PARAS[k]}</p>`).join('');
  box.scrollTop = 0;
}

function initParts() {
  document.querySelector('.ay-band').addEventListener('click', (e) => {
    const b = e.target.closest('button[data-i]');
    if (b) showPart(+b.dataset.i);
  });
  showPart(0);
}

