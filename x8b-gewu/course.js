function initRead() {
  const box = document.getElementById('gwText');
  box.innerHTML = PARAS.map((p, i) => `<p><sup>${i + 1}</sup>${p}${NOTES[i] ? `<button type="button" class="pz" data-i="${i}">批</button>` : ''}</p>`).join('');
  box.addEventListener('click', (e) => {
    const b = e.target.closest('.pz');
    if (!b) return;
    const [q, a] = NOTES[+b.dataset.i];
    box.querySelectorAll('.pz').forEach((x) => x.classList.toggle('on', x === b));
    document.getElementById('gwNote').innerHTML = `<p class="gw-q"><small>旁批 · 第 ${+b.dataset.i + 1} 段</small>${q}</p>
      <button type="button" class="btn" id="gwShow">想好了，看提示</button><p class="tip gold" id="gwA" hidden>${a}</p>`;
    document.getElementById('gwShow').onclick = () => { document.getElementById('gwA').hidden = false; };
  });
}

