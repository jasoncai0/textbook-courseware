function initCards() {
  const deck = document.getElementById('ylDeck');
  const res = document.getElementById('ylRes');
  let picked = null;
  deck.innerHTML = CARDS.map((c, i) => `<button type="button" class="yl-card" data-i="${i}"><i>${i + 1}</i>${c.s}</button>`).join('');
  const done = () => document.querySelectorAll('.yl-in .yl-card').length;
  deck.addEventListener('click', (e) => {
    const card = e.target.closest('.yl-card');
    if (!card) return;
    picked = card;
    deck.querySelectorAll('.yl-card').forEach((c) => c.classList.toggle('sel', c === card));
    res.textContent = '放进哪一类？点上面的类别。';
  });
  document.querySelector('.yl-bins').addEventListener('click', (e) => {
    const bin = e.target.closest('.yl-bin');
    if (!bin || !picked) return;
    const c = CARDS[+picked.dataset.i];
    if (c.ok.includes(bin.dataset.k)) {
      picked.classList.remove('sel');
      picked.classList.add('right');
      bin.querySelector('.yl-in').appendChild(picked);
      const also = c.ok.filter((k) => k !== bin.dataset.k);
      res.innerHTML = `✓ ${c.why}${also.length ? `<br><small>也可以归入：${also.join('、')}</small>` : ''}`;
      picked = null;
      if (done() === CARDS.length) res.innerHTML += '<br><b>十二章全部归档！</b>';
    } else {
      picked.classList.remove('no');
      void picked.offsetWidth;
      picked.classList.add('no');
      res.textContent = `再想想：“${c.s}”更侧重哪一方面？`;
    }
  });
}

