/* 长卷：第 1~3 步依次展开一卷，第 4 步并排看全卷 */
const PANELS = 3;
function updateScroll(slide, step) {
  const strip = slide.querySelector('#thStrip');
  if (!strip) return;
  const all = step > PANELS;
  const idx = Math.max(0, Math.min(step, PANELS) - 1);
  slide.querySelector('#thView').classList.toggle('all', all);
  strip.style.transform = all ? 'none' : `translateX(${-idx * 100 / PANELS}%)`;
  strip.querySelectorAll('.th-panel').forEach((p, i) => p.classList.toggle('now', !all && i === idx && step > 0));
}

/* 路线图：最新出现的节点高亮 */
function updateRoute(slide, step) {
  if (!slide.classList.contains('s-route')) return;
  slide.querySelectorAll('.rt-node, .rt-list li').forEach((el) => el.classList.toggle('cur', +el.dataset.step === step));
}

function initWords() {
  const box = document.getElementById('words');
  box.innerHTML = WORDS.map((w) => `<button type="button" class="wcard"><small>${w.k}</small><b>${w.w}</b><span class="wa">${w.a}<em>${w.e}</em></span></button>`).join('');
  box.addEventListener('click', (e) => {
    const c = e.target.closest('.wcard');
    if (c) c.classList.toggle('open');
  });
}

window.LESSON = {
  init() {
    Narrative.init({ clues: CLUES, clueLabels: CLUE_LABELS, picks: PICKS, moments: MOMENTS });
    Poem.init();
    initWords();
  },
  onRender(slide, step) {
    Narrative.onRender(slide, step);
    updateScroll(slide, step);
    updateRoute(slide, step);
  },
};
