function initTree() {
  const detail = document.getElementById('evDetail');
  document.querySelectorAll('.chips-ev').forEach((box) => {
    const b = +box.dataset.b;
    box.innerHTML = EVIDENCE[b].map((e, i) => `<button type="button" class="ev" data-b="${b}" data-i="${i}">${e.n}</button>`).join('');
  });
  document.getElementById('tree').addEventListener('click', (e) => {
    const c = e.target.closest('.ev');
    if (!c) return;
    document.querySelectorAll('.ev').forEach((x) => x.classList.toggle('cur', x === c));
    const ev = EVIDENCE[+c.dataset.b][+c.dataset.i];
    detail.innerHTML = `<i>${ev.k}</i>${ev.t}`;
  });
}

