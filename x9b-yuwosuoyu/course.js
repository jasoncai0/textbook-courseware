/* ============ 类比天平：第 1 步鱼/熊掌倾斜，第 3 步换成生/义再倾斜 ============ */
const SCALE = [
  { l: '鱼', r: '熊掌', tilt: 0, v: '鱼，我所欲也；熊掌，亦我所欲也。' },
  { l: '鱼', r: '熊掌', tilt: 1, v: '舍鱼而取熊掌' },
  { l: '鱼', r: '熊掌', tilt: 1, v: '舍鱼而取熊掌' },
  { l: '生', r: '义', tilt: 1, v: '舍生而取义' },
  { l: '生', r: '义', tilt: 1, v: '舍生而取义' },
];
const TILT_DEG = 8;
const PAN_DROP = 29; // 200 × sin 8°

function updateScale(slide, step) {
  if (!slide.classList.contains('s-scale')) return;
  const s = SCALE[Math.min(step, SCALE.length - 1)];
  const $ = (id) => slide.querySelector(`#${id}`);
  $('ywBeam').style.transform = `rotate(${s.tilt * TILT_DEG}deg)`;
  $('ywPanL').style.transform = `translateY(${-s.tilt * PAN_DROP}px)`;
  $('ywPanR').style.transform = `translateY(${s.tilt * PAN_DROP}px)`;
  $('ywL').textContent = s.l;
  $('ywR').textContent = s.r;
  $('ywVerdict').textContent = s.v;
  slide.classList.toggle('deep', s.l === '生');
}

function initChart() {
  document.querySelectorAll('.yc-blank').forEach((b) => b.addEventListener('click', () => b.classList.add('open')));
}

function initWords() {
  const box = document.getElementById('words');
  box.innerHTML = WORDS.map((w) => `<button type="button" class="wcard"><small>${w.k}</small><b>${w.w}</b><span class="wa">${w.a}<em>${w.e}</em></span></button>`).join('');
  box.addEventListener('click', (e) => {
    const c = e.target.closest('.wcard');
    if (c) c.classList.toggle('open');
  });
}

window.LESSON = {
  init() {
    Narrative.init({ moments: MOMENTS });
    Poem.init();
    initChart();
    initWords();
  },
  onRender(slide, step) {
    Narrative.onRender(slide, step);
    updateScale(slide, step);
  },
};
