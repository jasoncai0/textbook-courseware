/* ---------- 舞台：最新一句台词的说话人亮起 ---------- */
function updateStage(slide, step) {
  if (!slide.classList.contains('s-stage')) return;
  const shown = [...slide.querySelectorAll('.ln')].filter((l) => +l.dataset.step <= step);
  const last = shown[shown.length - 1];
  slide.querySelectorAll('.ln').forEach((l) => l.classList.toggle('now', l === last));
  slide.querySelectorAll('.actor').forEach((a) => a.classList.toggle('speaking', Boolean(last) && a.dataset.who === last.dataset.who));
}

