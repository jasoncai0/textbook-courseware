function showZone(key) {
  const z = ZONES[key];
  document.querySelectorAll('#boatSvg .zone').forEach((g) => g.classList.toggle('cur', g.dataset.zone === key));
  document.getElementById('bzCard').innerHTML = `<h3>${z.name}</h3>
    <div class="bz-pic" style="background-image:url(assets/${z.pic}.jpg)"></div>
    <p class="bz-text">${z.text}</p>
    <ul class="bz-seat">${z.seat.map(([a, b]) => `<li><b>${a}</b>${b}</li>`).join('')}</ul>
    <p class="tip gold">${z.tip}</p>`;
}

function initBoat() {
  const svg = document.getElementById('boatSvg');
  svg.addEventListener('click', (e) => {
    const g = e.target.closest('.zone');
    if (g) showZone(g.dataset.zone);
  });
  svg.addEventListener('keydown', (e) => {
    const g = e.target.closest('.zone');
    if (g && (e.key === 'Enter' || e.key === ' ')) { e.preventDefault(); e.stopPropagation(); showZone(g.dataset.zone); }
  });
}

/* 数刻字：点一条加一次 */
function initCount() {
  const box = document.getElementById('hzIns');
  box.addEventListener('click', (e) => {
    const b = e.target.closest('button[data-n]');
    if (!b) return;
    b.classList.toggle('on');
    const sum = [...box.querySelectorAll('button.on')].reduce((s, x) => s + +x.dataset.n, 0);
    document.getElementById('hzSum').textContent = sum;
    box.parentElement.classList.toggle('done', sum === 34);
  });
}

