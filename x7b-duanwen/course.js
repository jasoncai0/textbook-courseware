function showLotus(i) {
  const l = LOTUS[i];
  document.querySelectorAll('.lotus .lp').forEach((g) => g.classList.toggle('cur', +g.dataset.i === i));
  document.getElementById('lotusCard').innerHTML = `<p class="lc-s">${l.s}</p><p class="lc-w"><small>莲（物）</small>${l.w}</p><p class="lc-v"><small>君子（志）</small>${l.v}</p>`;
}
function initLotus() {
  document.querySelector('.lotus').addEventListener('click', (e) => {
    const g = e.target.closest('.lp');
    if (g) showLotus(+g.dataset.i);
  });
}

/* 陋室铭：每多一层“不陋”，“陋”字淡一分 */
function updateSeal(slide, step) {
  if (!slide.classList.contains('s-lou')) return;
  const LAST = 6;
  const p = Math.min(1, Math.max(0, (step - 1) / (LAST - 1)));
  const seal = document.getElementById('louSeal');
  seal.style.setProperty('--p', p.toFixed(2));
  seal.classList.toggle('done', step >= LAST);
}

