function initRoute() {
  const info = document.getElementById('routeInfo');
  document.getElementById('beiSvg').addEventListener('click', (e) => {
    const z = e.target.closest('[data-k]');
    if (!z) return;
    const k = z.dataset.k;
    document.querySelectorAll('#beiSvg [data-k]').forEach((x) => x.classList.toggle('sel', x.dataset.k === k));
    info.innerHTML = STOPS[k];
  });
}

