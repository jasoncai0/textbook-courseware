/* 愿景对比滑杆：右图（愿景）从右往左覆盖 */
function initVision() {
  const box = document.getElementById('vsBox');
  const range = document.getElementById('vsRange');
  const set = (v) => box.style.setProperty('--x', `${v}%`);
  range.addEventListener('input', () => set(range.value));
  set(range.value);
}

/* 背诵：三首切换 */
function initTabs() {
  const tabs = document.getElementById('tsTabs');
  tabs.addEventListener('click', (e) => {
    const b = e.target.closest('[data-t]');
    if (!b) return;
    tabs.querySelectorAll('.btn').forEach((x) => x.classList.toggle('solid', x === b));
    document.querySelectorAll('.ts-rec .recite').forEach((r, i) => r.classList.toggle('on', i === +b.dataset.t));
  });
}

