/* ================= 咏雪 · 比喻比高下：每行一项标准，点一下揭晓 ================= */
const BI = [
  { k: '颜色', a: '白', b: '白', win: 0, why: '都写出了雪的白，打平。' },
  { k: '形状', a: '颗粒', b: '絮片', win: 2, why: '大雪纷纷是一片片的，柳絮更像；若是雪粒，盐更像。' },
  { k: '动态', a: '直直下落', b: '随风飘舞', win: 2, why: '“因风起”写出雪的轻盈、飞舞，盐是沉沉地落下。' },
  { k: '意境', a: '平实', b: '春意、诗意', win: 2, why: '柳絮让人想到春天，寒雪日里有了暖意和美感。' },
];
function initBi() {
  const box = document.getElementById('biRows');
  box.innerHTML = BI.map((r, i) => `<button type="button" class="bi-row" data-i="${i}"><span class="ba">${r.a}</span><b>${r.k}</b><span class="bb">${r.b}</span><small>${r.why}</small></button>`).join('');
  box.addEventListener('click', (e) => {
    const row = e.target.closest('.bi-row');
    if (!row) return;
    const r = BI[+row.dataset.i];
    row.classList.add('open', r.win === 0 ? 'tie' : 'b-win');
  });
}

