function initWords() {
  const box = document.getElementById('words');
  box.innerHTML = WORDS.map((w) => `<button type="button" class="wcard"><small>${w.k}</small><b>${w.w}</b><span class="wa">${w.a}<em>${w.e}</em></span></button>`).join('');
  box.addEventListener('click', (e) => {
    const c = e.target.closest('.wcard');
    if (c) c.classList.toggle('open');
  });
}

/* 长卷：第 1~4 步依次展开一卷，第 5 步收拢看全卷 */
const PANELS = 4;
function updateScroll(slide, step) {
  const strip = slide.querySelector('#scStrip');
  if (!strip) return;
  const all = step > PANELS;
  const idx = Math.max(0, Math.min(step, PANELS) - 1);
  slide.querySelector('#scView').classList.toggle('all', all);
  strip.style.transform = all ? 'none' : `translateX(${-idx * 100 / PANELS}%)`;
  strip.querySelectorAll('.sc-panel').forEach((p, i) => p.classList.toggle('now', !all && i === idx && step > 0));
  slide.querySelectorAll('#scMap span').forEach((s, i) => s.classList.toggle('cur', all ? i === PANELS : i === idx));
}

